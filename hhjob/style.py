"""Проверка стиля. Ровно те правила, которые ломают текст чаще всего.

Запускать перед отправкой: hhjob lint письмо.md
"""

from __future__ import annotations

import re

RULES: list[tuple[str, str, str]] = [
    ("длинное тире", r"[—–]", "заменить на запятую, двоеточие или перестроить фразу"),
    ("буква ё", r"[ёЁ]", "писать е"),
    ("многоточие", r"\.\.\.|…", "убрать или переписать"),
    ("знак рубля", r"₽", "писать руб."),
    ("диапазон через дефис", r"\b\d+\s*-\s*\d+\b", "писать «от 80 000 до 100 000»"),
    ("двойной пробел", r"[ \t]{2,}", "убрать"),
    ("пробел перед знаком", r"\s+[,.;:!?]", "убрать"),
    ("клише", r"не просто\s+\w+,?\s+а\s+", "переписать без противопоставления"),
    ("канцелярит", r"\bявляется\b|\bданн(ый|ая|ые|ых)\b", "сказать проще"),
    ("риторический вопрос", r"\b(не так ли|правда ли)\b", "убрать"),
]

WORD_NUMBERS = [
    "ноль", "один", "одна", "одно", "два", "две", "три", "четыре", "пять",
    "шесть", "семь", "восемь", "девять", "десять",
]


def lint(text: str) -> list[tuple[str, str, str]]:
    """Возвращает список (правило, фрагмент, что делать)."""
    out = []
    for name, pattern, fix in RULES:
        for m in re.finditer(pattern, text):
            frag = text[max(0, m.start() - 25) : m.end() + 25].replace("\n", " ")
            out.append((name, frag.strip(), fix))
    for word in WORD_NUMBERS:
        for m in re.finditer(rf"\b{word}\b", text, re.I):
            frag = text[max(0, m.start() - 25) : m.end() + 25].replace("\n", " ")
            out.append(("число словом", frag.strip(), "поставить цифру"))
    return out
